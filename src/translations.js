// Hook for using translations
export function useLanguage() {
  const [language, setLanguage] = React.useState(localStorage.getItem('language') || 'it');
  
  React.useEffect(() => {
    localStorage.setItem('language', language);
  }, [language]);

  return {
    t: translations[language],
    language,
    setLanguage,
  };
}

